#!/usr/bin/env python3
"""
Production kernel-correction fits (finite Gaussian basis, B=14).

Implements the fitting procedure of the manuscript Sec. "Learning the kernel
correction" for all released fit families:

  pernucleus : one (delta g, s) per nucleus            -> kernels/per_nucleus/eg_PN14_<TAG>.dat
  shared     : one (delta g, s) for O16+Ca40+A80       -> kernels/universal/eg_SH14.dat
  shared_nopath : the shared fit WITHOUT the selected-path energy-rise rows
               (the "preliminary" correction of the manuscript, whose A=80
               relaxation develops the central-depletion artifact; used for
               the released s2-scan and quadrature diagnostics)
                                                        -> kernels/diagnostics/eg_SHNP14.dat
  no_tail    : per-nucleus O16/Ca40 without the surface-tail band and
               tail-margin penalty (diagnostic of Fig. "light")
                                                        -> kernels/diagnostics/eg_NT14_<TAG>.dat
  value_only : O16 with the NLF-value block only (diagnostic of Fig. "contrast")
                                                        -> kernels/diagnostics/eg_VO14_O16.dat

Data blocks (structure identical to the released GP machinery in gp_fit.py;
only the basis differs):
  1. chi-value data            (mask rho>1e-6, weight wch)
  2. EL-potential data         (mask rho>1e-5, weight wEL, eta=BETA)
  3. exact energy equality     (bordered KKT, one per training nucleus)
  4. surface-tail band         (mask mT, weight wT, eta=ETAT)
  5. tail-margin penalty       (band mH, chi_min=5, active set)
  6. selected-path energy-rise penalty (shared only; eps=2 MeV, weight 10,
     normalization (10 MeV)^2; trial densities in scripts/path_data/,
     generated by make_paths.py; rows are rebuilt here at run time)

Released algorithm settings (fixed):
  active-set repeated penalized least squares, 60 damped updates (damping 0.5);
  per-nucleus (eta_H, ridge, s_reg) = (120, 3e-3, 3e-2);
  shared     (eta_H, ridge, s_reg) = (12, 1e-2, 1e-2);
  no_tail / value_only reuse the per-nucleus settings without the dropped
  blocks. The ridge acts on the kernel coefficients and s_reg on the shift;
  both regularize otherwise ill-conditioned directions and are part of the
  released fit definition. Exact energy equalities are enforced by the KKT
  border and are unaffected by either regularizer.

Inputs (all released): inputs/ks/ks_<TAG>_nr250.dat,
results/reference/ks_nlf_<TAG>.dat, scripts/gp_data/teacher_ddkf_<TAG>.dat,
scripts/path_data/path_A80_xi*.dat. Requires numpy + scipy only.
"""
import os
import sys
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GPD = os.path.join(ROOT, "scripts", "gp_data")
PATHD = os.path.join(ROOT, "scripts", "path_data")

pi = np.pi
C = 20.73553
cTF = 0.6 * (3 * pi * pi) ** (2.0 / 3.0)
cNL = (96.0 / 125.0) * (3 * pi * pi) ** (2.0 / 3.0)
cCORR = (21.0 / 125.0) * (3 * pi * pi) ** (2.0 / 3.0)
NMU = 64
XKG, WKG = np.polynomial.legendre.leggauss(NMU)

t0, t1s, t2s, t3s, x2s, gam = -2931.70, 320.62, -337.41, 18708.97, -0.53732, 1.0 / 6.0
CG2 = 9 * t1s - 5 * t2s - 4 * t2s * x2s

B = 14
YTAB = np.linspace(0.0, 25.0, 2501)
NUCS = ("O16", "Ca40", "A80", "A140")
BANDS = {"O16": ((4.5, 8.0), (8.0, 11.5)), "Ca40": ((4.5, 8.0), (8.0, 11.5)),
         "A80": ((5.5, 9.0), (9.0, 13.0)), "A140": ((5.5, 9.0), (9.0, 13.0))}
BETA = {"O16": 2.0, "Ca40": 2.0, "A80": 12.0, "A140": 12.0}
ETAT = {"O16": 1.2, "Ca40": 0.3, "A80": 0.3, "A140": 0.3}
CHI_MIN, EPS_S = 5.0, 2.0
NIT, DAMP = 60, 0.5
SET_PN = dict(eta_h=120.0, ridge=3e-3, sreg=3e-2)
SET_SH = dict(eta_h=12.0, ridge=1e-2, sreg=1e-2)


def base_dimensionless_kernel(y, xqmax=80.0, nq=6000):
    q = np.linspace(1e-9, xqmax, nq + 1)
    x = q / 2.0
    with np.errstate(divide="ignore", invalid="ignore"):
        l = 0.5 * (1 + (1 - x ** 2) / (2 * x) * np.log(np.abs((1 + x) / (1 - x))))
    l = np.where(np.isfinite(l), l, 0.5)
    l1 = (5.0 / 8.0) * (1.0 / np.maximum(l, 1e-12) - 3 * x ** 2 + 3.0 / 5.0)
    out = np.zeros_like(y)
    for i, Y in enumerate(np.maximum(y, 1e-9)):
        out[i] = np.trapezoid(l1 * np.sin(q * Y) * q, q) / (2 * pi ** 2 * Y)
    return out


def tf_neutralized_basis():
    ref = np.exp(-((YTAB / 3.5) ** 2))
    Jref = np.trapezoid(YTAB ** 2 * ref, YTAB)
    tabs = []
    for c in range(B):
        raw = np.exp(-(((YTAB - c) / 0.9) ** 2))
        tabs.append(raw - (np.trapezoid(YTAB ** 2 * raw, YTAB) / Jref) * ref)
    return tabs


def spline_pair(tab):
    from scipy.interpolate import CubicSpline
    cs = CubicSpline(YTAB, tab, bc_type="natural")
    dcs = cs.derivative()
    ymax = YTAB[-1]
    fn = lambda y: np.where(y <= ymax, cs(np.clip(y, 0, ymax)), 0.0)
    dfn = lambda y: np.where(y <= ymax, dcs(np.clip(y, 0, ymax)), 0.0)
    return fn, dfn


def tau_response(r, w, rho, fn):
    rho = np.maximum(rho, 0.0)
    g56 = rho ** (5.0 / 6.0)
    Vh = 2 * pi * r ** 2 * w * g56
    t = 1.5 * pi * pi * (rho[:, None] + rho[None, :])
    kf = np.cbrt(t)
    R2 = r[:, None] ** 2 + r[None, :] ** 2
    rij = 2 * np.outer(r, r)
    acc = np.zeros(len(r))
    for k in range(NMU):
        Rk = np.sqrt(np.maximum(R2 - rij * XKG[k], 0.0))
        acc += WKG[k] * ((t * fn(kf * Rk)) @ Vh)
    return cNL * g56 * acc


def v_response(r, w, rho, fn, dfn):
    rho = np.maximum(rho, 0.0)
    g56 = rho ** (5.0 / 6.0)
    Vh = 2 * pi * r ** 2 * w * g56
    t = 1.5 * pi * pi * (rho[:, None] + rho[None, :])
    kf = np.cbrt(t)
    R2 = r[:, None] ** 2 + r[None, :] ** 2
    rij = 2 * np.outer(r, r)
    Jg = np.zeros(len(r))
    Jr = np.zeros(len(r))
    for k in range(NMU):
        Rk = np.sqrt(np.maximum(R2 - rij * XKG[k], 0.0))
        y = kf * Rk
        Jg += WKG[k] * ((t * fn(y)) @ Vh)
        Jr += WKG[k] * ((fn(y) + (y / 3.0) * dfn(y)) @ Vh)
    return C * cNL * ((5.0 / 3.0) * np.maximum(rho, 1e-30) ** (-1.0 / 6.0) * Jg
                      + 3.0 * pi * pi * g56 * Jr)


def base_potential(r, w, rho, gb_pair):
    phi = np.sqrt(np.maximum(rho, 1e-30))
    lap_phi = np.gradient(r ** 2 * np.gradient(phi, r), r) / np.maximum(r ** 2, 1e-12)
    v_vw = -C * lap_phi / phi
    v_nl = v_response(r, w, rho, *gb_pair)
    v_c = -C * (5.0 / 3.0) * cCORR * np.maximum(rho, 0.0) ** (2.0 / 3.0)
    rt = 2.0 * np.maximum(rho, 0.0)
    lap_rt = np.gradient(r ** 2 * np.gradient(rt, r), r) / np.maximum(r ** 2, 1e-12)
    v_skp = 0.75 * t0 * rt + ((2 + gam) / 16.0) * t3s * rt ** (1 + gam) - (CG2 / 32.0) * lap_rt
    return v_vw + v_nl + v_c + v_skp


def base_energy(r, w, rho, gb_pair):
    """E_base[rho] (s=0), MeV; used only for path-row base differences."""
    rho = np.maximum(rho, 0.0)
    vol = 4 * pi * r ** 2 * w
    phi = np.sqrt(np.maximum(rho, 1e-30))
    dphi = np.gradient(phi, r)
    T_vw = C * np.sum(vol * dphi ** 2)
    tau_nl = tau_response(r, w, rho, gb_pair[0])
    T_nl = C * np.sum(vol * tau_nl)
    T_corr = -C * cCORR * np.sum(vol * rho ** (5.0 / 3.0))
    rt = 2 * rho
    drt = np.gradient(rt, r)
    E_skp = np.sum(vol * (0.375 * t0 * rt ** 2 + t3s / 16.0 * rt ** (2 + gam))) \
        + (CG2 / 64.0) * np.sum(vol * drt ** 2)
    return 2 * (T_vw + T_nl + T_corr) + E_skp


def load_nucleus(nuc, basis_tabs, gb_pair, verbose=True):
    d = np.loadtxt(os.path.join(ROOT, "inputs", "ks", "ks_%s_nr250.dat" % nuc))
    r, rho = d[:, 0], d[:, 1]
    w = np.full_like(r, r[1] - r[0])
    k5 = np.loadtxt(os.path.join(ROOT, "results", "reference", "ks_nlf_%s.dat" % nuc))
    I = lambda x: np.interp(r, k5[:, 0], x)
    tauTF = np.maximum(I(k5[:, 2]), 1e-30)
    tauvW, tauKS = I(k5[:, 3]), I(k5[:, 4])
    t8 = np.loadtxt(os.path.join(GPD, "teacher_ddkf_%s.dat" % nuc))
    taudd = np.interp(r, t8[:, 0], t8[:, 6])
    chiKS = (tauKS - tauvW) / tauTF
    chidd = (taudd - tauvW) / tauTF
    Dt, Vb = [], []
    for tab in basis_tabs:
        fn, dfn = spline_pair(tab)
        Dt.append(tau_response(r, w, rho, fn))
        Vb.append(v_response(r, w, rho, fn, dfn))
    rho53 = np.maximum(rho, 1e-30) ** (5.0 / 3.0)
    Xc = np.column_stack([dt / tauTF for dt in Dt] + [-rho53 / tauTF])
    Vs = -(5.0 * C / 3.0) * np.maximum(rho, 0.0) ** (2.0 / 3.0)
    V = np.column_stack(Vb + [Vs])
    V0 = base_potential(r, w, rho, gb_pair)
    vol = 4 * pi * r ** 2 * (r[1] - r[0])
    g = np.array([np.sum(vol * dt) for dt in Dt] + [float(-np.sum(vol * rho53))])
    tgt = float(np.sum(vol * (tauKS - taudd)))
    boostw = 3.2 if nuc in ("O16", "Ca40") else 3.9
    J = 2 * np.abs(chiKS) / (1 + chiKS ** 2) ** 2
    wch = (r ** 2 + 0.7) * rho * (1 + 8 * np.exp(-((r / boostw) ** 2))) * J ** 2
    (tl, th_), (h1, h2) = BANDS[nuc]
    out = dict(nuc=nuc, r=r, rho=rho, w=w, Xc=Xc, V=V, V0=V0, Dt=Dt,
               ych=chiKS - chidd, yv=-V0, chidd=chidd, chiKS=chiKS,
               g=g, tgt=tgt, wch=wch,
               wT=r ** 2 * np.maximum(rho, 1e-30) ** 0.4 / (1 + (chiKS / 8.0) ** 2),
               wEL=(r ** 2 + 0.7) * rho,
               mB=rho > 1e-6, mE=rho > 1e-5,
               mT=(r > tl) & (r < th_), mH=(r >= h1) & (r < h2))
    if verbose:
        print("  [%s] responses assembled (B=%d)" % (nuc, B))
    return out


def path_rows(dA80, basis_tabs, gb_pair):
    """Rebuild affine energy-rise rows (q, dE_base) from stored trial densities."""
    rows = []
    if not os.path.isdir(PATHD):
        return rows
    r, w = dA80["r"], dA80["w"]
    vol = 4 * pi * r ** 2 * (r[1] - r[0])
    rho0 = dA80["rho"]
    E0 = base_energy(r, w, rho0, gb_pair)
    I0 = np.array([2 * C * np.sum(vol * dt) for dt in dA80["Dt"]]
                  + [-2 * C * np.sum(vol * np.maximum(rho0, 0.0) ** (5.0 / 3.0))])
    for f in sorted(os.listdir(PATHD)):
        if not (f.startswith("path_A80_") and f.endswith(".dat")):
            continue
        p = np.loadtxt(os.path.join(PATHD, f))
        rho = np.interp(r, p[:, 0], p[:, 1])
        dE = base_energy(r, w, rho, gb_pair) - E0
        Ij = np.array([2 * C * np.sum(vol * tau_response(r, w, rho, spline_pair(tab)[0]))
                       for tab in basis_tabs]
                      + [-2 * C * np.sum(vol * np.maximum(rho, 0.0) ** (5.0 / 3.0))])
        rows.append(("A80", f, Ij - I0, float(dE)))
    return rows


def solve(dsets, blocks, eta_h, ridge, sreg, paths=(), nit=NIT, damp=DAMP):
    ntr = len(dsets)
    nun = B + 1 + ntr
    RA, RY, RIV = [], [], []
    for i, d in enumerate(dsets):
        cand = [("value", d["mB"], "X", d["ych"], d["wch"], 1.0, False),
                ("el", d["mE"], "V", d["yv"], d["wEL"], BETA[d["nuc"]], True),
                ("band", d["mT"], "X", d["ych"], d["wT"], ETAT[d["nuc"]], False)]
        for name, mask, cols, yv, wgt, eta, mu in cand:
            if name not in blocks:
                continue
            A = np.zeros((int(mask.sum()), nun))
            A[:, :B + 1] = d["Xc"][mask] if cols == "X" else d["V"][mask]
            if mu:
                A[:, B + 1 + i] = -1.0
            y = yv[mask]
            wm = wgt[mask]
            RA.append(A)
            RY.append(y)
            RIV.append(eta * wm / np.sum(wm * y ** 2))
    use_eq = "equality" in blocks
    G = np.zeros((ntr, nun))
    T = np.zeros(ntr)
    for i, d in enumerate(dsets):
        G[i, :B + 1] = d["g"]
        T[i] = d["tgt"]
    H0 = np.zeros((nun, nun))
    b0 = np.zeros(nun)
    for A, y, iv in zip(RA, RY, RIV):
        H0 += A.T @ (A * iv[:, None])
        b0 += A.T @ (iv * y)
    c = np.zeros(nun)
    for _ in range(nit):
        H = H0.copy()
        b = b0.copy()
        H[:B, :B] += ridge * np.eye(B)
        H[B, B] += sreg
        for j in range(ntr):
            H[B + 1 + j, B + 1 + j] += 1e-10
        if "margin" in blocks:
            for d in dsets:
                chiH = d["chidd"][d["mH"]] + d["Xc"][d["mH"]][:, :B + 1] @ c[:B + 1]
                viol = chiH < CHI_MIN
                if viol.any():
                    AH = np.zeros((int(viol.sum()), nun))
                    AH[:, :B + 1] = d["Xc"][d["mH"]][viol]
                    yH = (CHI_MIN - d["chidd"][d["mH"]])[viol]
                    sH = max(np.sum(yH ** 2), 1e-12)
                    H += eta_h * (AH.T @ AH) / sH
                    b += eta_h * (AH.T @ yH) / sH
        for (_, _, q, dEb) in paths:
            if dEb + float(q @ c[:B + 1]) < EPS_S:
                row = np.zeros(nun)
                row[:B + 1] = q
                H += 10.0 * np.outer(row, row) / 100.0
                b += 10.0 * row * (EPS_S - dEb) / 100.0
        if use_eq:
            KKT = np.zeros((nun + ntr, nun + ntr))
            KKT[:nun, :nun] = H
            KKT[:nun, nun:] = G.T
            KKT[nun:, :nun] = G
            cn = np.linalg.solve(KKT, np.concatenate([b, T]))[:nun]
        else:
            cn = np.linalg.solve(H, b)
        c = damp * cn + (1 - damp) * c
    return c


def diagnostics(d, th, fh, paths=()):
    chi = d["chidd"] + d["Xc"][:, :B + 1] @ th[:B + 1]
    nlf = 1.0 / (1.0 + chi ** 2)
    nlfKS = 1.0 / (1.0 + d["chiKS"] ** 2)
    r, rho = d["r"], d["rho"]
    cut = 7.5 if d["nuc"] in ("O16", "Ca40") else (9.0 if d["nuc"] == "A80" else 10.0)
    m = r < cut
    wgt = r ** 2 * rho
    dfix = float(np.sqrt(np.sum((wgt * (nlf - nlfKS) ** 2)[m]) / np.sum(wgt[m])))
    line = ("%-5s fixed-density d = %.4f   min chi(diag band) = %8.2f (soft target >= %g)"
            % (d["nuc"], dfix, chi[d["mH"]].min(), CHI_MIN))
    print("   " + line)
    fh.write(line + "\n")
    for (_, f, q, dEb) in paths:
        de = dEb + float(q @ th[:B + 1])
        fh.write("   path %-22s Delta E = %+7.4f MeV (soft target >= %g)\n" % (f, de, EPS_S))
    return dfix


def write_kernel(dirname, tag, th, basis):
    dg = sum(cb * tab for cb, tab in zip(th[:B], basis))
    os.makedirs(os.path.join(ROOT, "kernels", dirname), exist_ok=True)
    np.savetxt(os.path.join(ROOT, "kernels", dirname, "%s.dat" % tag),
               np.column_stack([YTAB, dg]),
               header="y delta_g(y)   [kernel_fit.py, B=%d TF-neutralized Gaussians]" % B)
    np.save(os.path.join(ROOT, "kernels", dirname, "%s_coef.npy" % tag), th)
    with open(os.path.join(ROOT, "kernels", dirname, "%s_shift.txt" % tag), "w") as f:
        f.write("%.6f\n" % th[B])
    return float(np.max(np.abs(dg)))


def main():
    fams = sys.argv[1:] or ["pernucleus", "shared", "shared_nopath", "no_tail", "value_only"]
    print("[kernel_fit] basis + base kernel")
    basis = tf_neutralized_basis()
    gbp = spline_pair(base_dimensionless_kernel(YTAB))
    data = {n: load_nucleus(n, basis, gbp) for n in NUCS}
    fh = open(os.path.join(ROOT, "scripts", "fit_report.txt"), "w")
    full = {"value", "el", "band", "margin", "equality"}

    if "pernucleus" in fams:
        print("[kernel_fit] per-nucleus fits", SET_PN)
        fh.write("== per-nucleus (B=%d, %s)\n" % (B, SET_PN))
        for n in NUCS:
            th = solve([data[n]], full, **SET_PN)
            mx = write_kernel("per_nucleus", "eg_PN14_%s" % n, th, basis)
            print("  %s: s=%+.5f mu=%.4f max|dg|=%.3f" % (n, th[B], th[B + 1], mx))
            fh.write("%s: s=%+.6f mu=%.5f max|dg|=%.4f\n" % (n, th[B], th[B + 1], mx))
            diagnostics(data[n], th, fh)

    if "shared" in fams:
        paths = path_rows(data["A80"], basis, gbp)
        print("[kernel_fit] shared fit", SET_SH, "(%d path rows)" % len(paths))
        fh.write("== shared (B=%d, %s, %d path rows)\n" % (B, SET_SH, len(paths)))
        th = solve([data[n] for n in ("O16", "Ca40", "A80")], full, paths=paths, **SET_SH)
        mx = write_kernel("universal", "eg_SH14", th, basis)
        print("  shared: s=%+.5f max|dg|=%.3f" % (th[B], mx))
        fh.write("shared: s=%+.6f max|dg|=%.4f\n" % (th[B], mx))
        for n in NUCS:
            diagnostics(data[n], th, fh, paths=paths if n == "A80" else ())

    if "shared_nopath" in fams:
        print("[kernel_fit] shared fit WITHOUT energy-rise rows (preliminary)", SET_SH)
        fh.write("== shared_nopath (B=%d, %s, 0 path rows)\n" % (B, SET_SH))
        th = solve([data[n] for n in ("O16", "Ca40", "A80")], full, paths=(), **SET_SH)
        mx = write_kernel("diagnostics", "eg_SHNP14", th, basis)
        print("  shared_nopath: s=%+.5f max|dg|=%.3f" % (th[B], mx))
        fh.write("shared_nopath: s=%+.6f max|dg|=%.4f\n" % (th[B], mx))
        for n in NUCS:
            diagnostics(data[n], th, fh)

    if "shared_nopath" in fams:
        print("[kernel_fit] shared fit WITHOUT energy-rise rows (preliminary-style)", SET_SH)
        fh.write("== shared_nopath (B=%d, %s, 0 path rows)\n" % (B, SET_SH))
        th = solve([data[n] for n in ("O16", "Ca40", "A80")], full, paths=(), **SET_SH)
        mx = write_kernel("diagnostics", "eg_NP14_shared", th, basis)
        print("  shared_nopath: s=%+.5f max|dg|=%.3f" % (th[B], mx))
        fh.write("shared_nopath: s=%+.6f max|dg|=%.4f\n" % (th[B], mx))
        for n in NUCS:
            diagnostics(data[n], th, fh)

    if "no_tail" in fams:
        print("[kernel_fit] no-tail diagnostics (O16, Ca40)")
        fh.write("== no_tail diagnostics\n")
        for n in ("O16", "Ca40"):
            th = solve([data[n]], {"value", "el", "equality"}, **SET_PN)
            mx = write_kernel("diagnostics", "eg_NT14_%s" % n, th, basis)
            print("  %s(no tail): s=%+.5f max|dg|=%.3f" % (n, th[B], mx))
            fh.write("%s: s=%+.6f max|dg|=%.4f\n" % (n, th[B], mx))
            diagnostics(data[n], th, fh)

    if "value_only" in fams:
        print("[kernel_fit] value-only diagnostic (O16)")
        fh.write("== value_only diagnostic\n")
        th = solve([data["O16"]], {"value"}, **SET_PN)
        mx = write_kernel("diagnostics", "eg_VO14_O16", th, basis)
        print("  O16(value only): s=%+.5f max|dg|=%.3f" % (th[B], mx))
        fh.write("O16: s=%+.6f max|dg|=%.4f\n" % (th[B], mx))
        diagnostics(data["O16"], th, fh)

    fh.close()
    print("[kernel_fit] done; scripts/fit_report.txt")


if __name__ == "__main__":
    main()
