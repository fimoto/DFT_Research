#!/usr/bin/env python3
"""
Consistent KS reference total energies E_KS = 2*C*Int tau_KS + E_SkP[rho_KS].

Evaluated with the same mass constant as the released solver
(C = hbar^2/2m = 20.73553 MeV fm^2) on the nr=500 KS reference tables
(results/reference/ks_nlf_<TAG>.dat: columns r, rho_species, tau_TF, tau_vW,
tau_KS, NLF_KS). The interaction part uses the simplified SkP functional of the
manuscript. Cross-check: on the same density the Fortran derivative path
(E_SkP_total_MeV) agrees with this python evaluation to <1 keV.

Writes results/reference/ks_reference_energies.dat.
"""
import os
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = 20.73553
t0, t1s, t2s, t3s, x2s, gam = -2931.70, 320.62, -337.41, 18708.97, -0.53732, 1.0 / 6.0
CG2 = 9 * t1s - 5 * t2s - 4 * t2s * x2s
A = {"O16": (16, 8), "Ca40": (40, 20), "A80": (80, 40), "A140": (140, 70)}

lines = ["# KS-SkP reference total energies E_KS[rho_KS] (MeV), N=Z, no spin-orbit,",
         "# no Coulomb; C = hbar^2/2m = 20.73553 MeV fm^2 (same constant as the",
         "# released solver). Generated by scripts/ks_total_energy.py from the",
         "# nr=500 KS reference tables.",
         "# Columns: label  A  npart_species  kf_const  E_KS_MeV"]
for tag, (a, nq) in A.items():
    d = np.loadtxt(os.path.join(ROOT, "results", "reference", "ks_nlf_%s.dat" % tag))
    r, rho_q, tauKS = d[:, 0], d[:, 1], d[:, 4]
    rho = 2 * rho_q
    T = 2 * C * np.trapezoid(4 * np.pi * r ** 2 * tauKS, r)
    drho = np.gradient(rho, r)
    Eint = np.trapezoid(4 * np.pi * r ** 2 * (0.375 * t0 * rho ** 2
                                              + t3s / 16.0 * rho ** (2 + gam)), r) \
        + (CG2 / 64.0) * np.trapezoid(4 * np.pi * r ** 2 * drho ** 2, r)
    E = T + Eint
    print("%-5s E_KS = %.3f MeV" % (tag, E))
    lines.append("%-5s  %4d  %3d  0.80  %10.3f" % (tag, a, nq, E))

out = os.path.join(ROOT, "results", "reference", "ks_reference_energies.dat")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out)
